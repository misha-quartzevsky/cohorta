// Телефонный редактор, 390x844: node scripts/editor-m-shots.mjs <папка> [префикс]
import { chromium } from "playwright";

const out = process.argv[2];
const pre = process.argv[3] ?? "";
const BASE = process.env.BASE ?? "http://127.0.0.1:5173";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const p = await ctx.newPage();
await p.goto(`${BASE}/login`);
await p.fill('input[type="email"]', process.env.DEMO_EMAIL);
await p.fill('input[type="password"]', process.env.DEMO_PASSWORD);
await p.click('button[type="submit"]');
await p.waitForURL(/\/s\//, { timeout: 15000 });
const shot = (n) => p.screenshot({ path: `${out}/${pre}${n}.png` });
await p.goto(`${BASE}/s/demo/math-analysis/limit-of-sequence`);
await p.waitForTimeout(2000);
await shot("editor");
await p.goto(`${BASE}/s/demo/math-analysis/limit-of-sequence/edit`);
await p.waitForTimeout(2000);
await shot("editor-live");
await p.getByRole("button", { name: "Открыть содержание" }).tap();
await p.waitForTimeout(500);
await shot("toc");
await p.goto(`${BASE}/s/demo/math-analysis/limit-of-sequence`);
await p.waitForTimeout(1500);
await p.getByRole("button", { name: "Меню лекции" }).tap();
await p.waitForTimeout(500);
await shot("menu");
console.log("overflow-x:", await p.evaluate(() => document.documentElement.scrollWidth - window.innerWidth));
await p.goto(`${BASE}/s/1/storitelling/test`);
await p.waitForTimeout(2000);
await shot("long");
await p.getByRole("button", { name: "Открыть содержание" }).tap();
await p.waitForTimeout(500);
await shot("toc-long");
await p.goto(`${BASE}/s/demo/math-analysis/b5-quiz-created`);
await p.waitForTimeout(1500);
await p.getByRole("button", { name: "Открыть содержание" }).tap();
await p.waitForTimeout(500);
await shot("toc-empty");
await p.goto(`${BASE}/note/zametka-test`);
await p.waitForTimeout(2000);
await shot("draft");
await p.getByRole("button", { name: "Открыть содержание" }).tap();
await p.waitForTimeout(500);
await shot("toc-zero");
await b.close();
