// «Новая карточка»: node scripts/b5-card-form.mjs <папка>. Созданные карточки удаляются.
import { chromium } from "playwright";
import PocketBase from "pocketbase";
const out = process.argv[2];
const BASE = process.env.BASE ?? "http://127.0.0.1:5173";
const pb = new PocketBase("http://127.0.0.1:8090");
await pb.collection("users").authWithPassword("asyaobraz17@gmail.com", "12345678");
const deck = (await pb.collection("decks").getFullList()).find((d) => d.slug);
const before = (await pb.collection("deck_cards").getFullList({ filter: `deck="${deck.id}"` })).length;
const b = await chromium.launch();
for (const [mode, vp, mobile] of [["desktop", { width: 1440, height: 900 }, false], ["mobile", { width: 390, height: 844 }, true]]) {
  const ctx = await b.newContext({ viewport: vp, hasTouch: mobile, isMobile: mobile });
  const p = await ctx.newPage();
  await p.goto(`${BASE}/login`);
  await p.fill('input[type="email"]', "asyaobraz17@gmail.com");
  await p.fill('input[type="password"]', "12345678");
  await p.click('button[type="submit"]');
  await p.waitForURL(/\/s\//);
  await p.goto(`${BASE}/decks/${deck.slug}`);
  await p.getByRole("button", { name: "Добавить карточку" }).click();
  await p.waitForTimeout(500);
  await p.screenshot({ path: `${out}/card-form-${mode}.png` });
  await p.getByRole("button", { name: /^Сохранить$/ }).click();
  await p.waitForTimeout(300);
  await p.screenshot({ path: `${out}/card-form-${mode}-empty-error.png` });
  await p.getByLabel("Вопрос").fill(`Тест ${mode}: вопрос?`);
  await p.getByLabel("Ответ").fill("Короткий ответ");
  await p.getByRole("button", { name: /Сохранить и/ }).click();
  await p.waitForTimeout(800);
  console.log(mode, "после «ещё»: окно открыто =", await p.getByRole("dialog").count(), "вопрос очищен =", (await p.getByLabel("Вопрос").inputValue()) === "");
  await p.getByLabel("Вопрос").fill(`Тест ${mode}: второй?`);
  await p.getByLabel("Ответ").fill("Второй ответ");
  const opts = await p.getByLabel(/^Лекция/).locator("option").allInnerTexts();
  console.log(mode, "лекций в списке:", opts.length - 1, "первая:", opts[1]);
  await p.screenshot({ path: `${out}/card-form-${mode}-lecture.png` });
  if (opts.length > 1) await p.getByLabel(/^Лекция/).selectOption({ index: 1 });
  await p.getByRole("button", { name: /^Сохранить$/ }).click();
  await p.waitForTimeout(1000);
  console.log(mode, "окно закрыто =", (await p.getByRole("dialog").count()) === 0, "в списке:", await p.getByText(`Тест ${mode}`).count());
  await p.screenshot({ path: `${out}/card-form-${mode}-after.png` });
  await ctx.close();
}
await b.close();
const all = await pb.collection("deck_cards").getFullList({ filter: `deck="${deck.id}"`, sort: "position,created" });
console.log("с лекцией:", all.filter((c) => c.lecture).length);
console.log("было", before, "стало", all.length, "последние:", all.slice(-4).map((c) => `${c.position}:${c.front.slice(0, 25)}`).join(" | "));
for (const c of all.filter((c) => c.front.includes("Тест desktop") || c.front.includes("Тест mobile"))) await pb.collection("deck_cards").delete(c.id);
