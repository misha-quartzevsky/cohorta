import { chromium } from "playwright";
const OUT = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 500 }, deviceScaleFactor: 2 });
const p = await ctx.newPage();
await p.goto("http://127.0.0.1:5173/login");
await p.fill('input[type="email"]', "asyaobraz17@gmail.com");
await p.fill('input[type="password"]', "12345678");
await p.click('button[type="submit"]');
await p.waitForURL(/\/s\//, { timeout: 15000 });
await p.goto("http://127.0.0.1:5173/s/demo/math-analysis/limit-of-sequence/edit");
await p.waitForTimeout(2000);
const ed = p.locator(".ProseMirror").first();
await ed.click();
await p.keyboard.press("Control+End");
await p.keyboard.press("Enter");
await p.keyboard.type("/");
await p.waitForTimeout(600);
const m = p.locator(".slash-menu").first();
console.log(await m.boundingBox());
await p.screenshot({ path: `${OUT}/m-slash.png` });
await b.close();
