function esc(value) {
  return String(value).replace(/"/g, '\\"');
}

migrate((app) => {
  const collection = app.findCollectionByNameOrId("universities");
  let created = 0;

  for (const uni of UNIVERSITIES) {
    const filter = `name = "${esc(uni.name)}" && city = "${esc(uni.city)}"`;
    const existing = app.findRecordsByFilter("universities", filter, "", 1, 0);
    if (existing.length > 0) continue;

    const record = new Record(collection, { name: uni.name, city: uni.city });
    app.save(record);
    created++;
  }

  console.log(`Seeded universities: ${created} new, ${UNIVERSITIES.length - created} already present`);
}, (app) => {
  // Rollback: снести только строки из этого списка (name+city), чужие данные не трогаем.
  for (const uni of UNIVERSITIES) {
    const filter = `name = "${esc(uni.name)}" && city = "${esc(uni.city)}"`;
    const rows = app.findRecordsByFilter("universities", filter, "", 1, 0);
    if (rows.length > 0) app.delete(rows[0]);
  }
})
